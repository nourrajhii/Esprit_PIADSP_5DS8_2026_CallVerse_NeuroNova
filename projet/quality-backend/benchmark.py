"""Compare saved Gemini reports against blinded human annotations.
Usage: python benchmark.py datasets/annotations_template.csv
Human labels are NOT generated by this script. Two independent annotators are recommended.
"""
import csv
import json
import math
import sqlite3
import sys
from pathlib import Path

from app import DB_PATH, WEIGHTS


def metrics(gold_file: Path):
    if not gold_file.exists() or not DB_PATH.exists():
        print('Annotations ou base de rapports absentes. Lance des évaluations puis renseigne les annotations humaines.'); return 1
    with sqlite3.connect(DB_PATH) as conn:
        rows = conn.execute('SELECT id,report_json FROM evaluations').fetchall()
    predictions = {key: json.loads(report) for key, report in rows}
    errors, truth, predicted = [], [], []
    with gold_file.open(encoding='utf-8-sig', newline='') as f:
        for line in csv.DictReader(f):
            key = line.get('conversation_id', '').strip()
            if not key or key not in predictions: continue
            try:
                human = sum(float(line[k + '_humaine']) * w for k, w in WEIGHTS.items())
            except (ValueError, KeyError): continue
            errors.append(predictions[key]['globalScore'] - human)
            flag = line.get('critique_humain', '').strip().lower()
            if flag in ('oui', 'non'):
                truth.append(flag == 'oui')
                predicted.append(predictions[key]['priority'] == 'critique')
    n = len(errors)
    print(f'Conversations appariées avec annotation humaine : {n}')
    if not n: print('Aucune correspondance : utilise les conversationId de /evaluations.'); return 1
    mae = sum(abs(e) for e in errors) / n
    rmse = math.sqrt(sum(e * e for e in errors) / n)
    print(f'MAE = {mae:.2f}/100 | RMSE = {rmse:.2f}/100')
    if len(truth):
        tp = sum(t and p for t, p in zip(truth, predicted)); fp = sum(not t and p for t,p in zip(truth,predicted)); fn = sum(t and not p for t,p in zip(truth,predicted))
        precision = tp / (tp+fp) if tp+fp else 0
        recall = tp / (tp+fn) if tp+fn else 0
        f1 = 2*precision*recall/(precision+recall) if precision+recall else 0
        print(f'Critiques : P={precision:.2f}, R={recall:.2f}, F1={f1:.2f} (TP={tp}, FP={fp}, FN={fn})')
    if n < 30:
        print('AVERTISSEMENT : échantillon petit / non représentatif, résultats exploratoires uniquement.')
    return 0


if __name__ == '__main__':
    sys.exit(metrics(Path(sys.argv[1] if len(sys.argv) > 1 else 'datasets/annotations_template.csv')))
